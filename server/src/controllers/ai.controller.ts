import { Response, NextFunction } from 'express';
import { AuthenticatedRequest } from '../middleware/auth.middleware.js';
import { AiAssistanceService } from '../services/ai.service.js';
import { User } from '../models/user.model.js';

// 1. SMART RESOURCE MATCHING
export const matchResourcesController = async (
  req: AuthenticatedRequest,
  res: Response,
  next: NextFunction
): Promise<void> => {
  try {
    const { requirements, category, location, date, timeSlot, equipmentSpecs, minRating } = req.body;

    let userProfile = null;
    if (req.user) {
      userProfile = await User.findById(req.user._id).lean();
    }

    const matchResults = await AiAssistanceService.matchResources(
      {
        requirements,
        category,
        location,
        date,
        timeSlot,
        equipmentSpecs,
        minRating,
      },
      userProfile
    );

    res.status(200).json({
      success: true,
      message: 'Smart resource matching completed successfully.',
      data: matchResults,
    });
  } catch (error) {
    next(error);
  }
};


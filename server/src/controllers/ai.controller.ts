// 3. SCHEDULING CONFLICT DETECTION
export const detectConflictsController = async (
  req: AuthenticatedRequest,
  res: Response,
  next: NextFunction
): Promise<void> => {
  try {
    const { resourceId, startTime, endTime, date, timeSlot, excludeBookingId } = req.body;

    if (!resourceId) {
      res.status(400).json({
        success: false,
        message: 'Resource ID is required for conflict detection.',
      });
      return;
    }

    const conflictAnalysis = await AiAssistanceService.detectSchedulingConflicts({
      resourceId,
      startTime: startTime || `${date}T09:00:00`,
      endTime: endTime || `${date}T12:00:00`,
      date,
      timeSlot,
      excludeBookingId,
    });

    res.status(200).json({
      success: true,
      message: conflictAnalysis.hasConflict
        ? 'Scheduling conflicts detected.'
        : 'Interval is conflict-free and available.',
      data: conflictAnalysis,
    });
  } catch (error) {
    next(error);
  }
};

